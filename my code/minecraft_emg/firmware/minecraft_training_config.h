#ifndef MINECRAFT_TRAINING_CONFIG_H
#define MINECRAFT_TRAINING_CONFIG_H

/* 참여자가 바뀌면 1~255 범위에서 변경한다. 0은 미설정으로 예약한다. */
#ifndef MINECRAFT_TRAINING_PARTICIPANT_ID
#define MINECRAFT_TRAINING_PARTICIPANT_ID 1U
#endif

#if MINECRAFT_TRAINING_PARTICIPANT_ID < 1U || \
    MINECRAFT_TRAINING_PARTICIPANT_ID > 255U
#error "MINECRAFT_TRAINING_PARTICIPANT_ID must be in 1..255"
#endif

/* BTN2 클릭 뒤 준비 시간과 기본 기록 시간. 기록 중 BTN2로 조기 종료할 수 있다. */
#define MINECRAFT_TRAINING_PREPARE_MS       3000U
#define MINECRAFT_TRAINING_RECORD_MS       10000U

/* Rev2.0 PhAI V2.2 User Custom 모듈 ID와 PC 송신 주기. */
#define MINECRAFT_TRAINING_MODULE_ID        0xF5U
#define MINECRAFT_TRAINING_STREAM_PERIOD_MS 10U

#if MINECRAFT_TRAINING_MODULE_ID < 0xF0U || \
    MINECRAFT_TRAINING_MODULE_ID > 0xFEU
#error "MINECRAFT_TRAINING_MODULE_ID must be in 0xF0..0xFE"
#endif

#if MINECRAFT_TRAINING_STREAM_PERIOD_MS < 1U
#error "MINECRAFT_TRAINING_STREAM_PERIOD_MS must be positive"
#endif

#endif /* MINECRAFT_TRAINING_CONFIG_H */
